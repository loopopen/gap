package xpostgres

import (
	"fmt"
	"regexp"
)

const maxIdentLen = 63

var identRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func quoteIdent(name string) (string, error) {
	if len(name) == 0 || len(name) > maxIdentLen || !identRE.MatchString(name) {
		return "", fmt.Errorf("invalid identifier %q", name)
	}
	return `"` + name + `"`, nil
}

func statusTypeSQL(schema, quotedSchema string) string {
	return fmt.Sprintf(`
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'status_enum'
        AND n.nspname = '%s'
    ) THEN
        CREATE TYPE %s."status_enum" AS ENUM ('Pending', 'Succeeded', 'Failed');
    END IF;
END
$$;`, schema, quotedSchema)
}

func publishedCreateSQL(table, statusType string) string {
	return fmt.Sprintf(
		"CREATE TABLE IF NOT EXISTS %s ("+
			`"id" bigint GENERATED BY DEFAULT AS IDENTITY,`+
			`"created_at" timestamptz NOT NULL,`+
			`"version" varchar(16) NOT NULL,`+
			`"topic" varchar(256) NOT NULL,`+
			`"status" %s NOT NULL,`+
			`"headers" text,`+
			`"payload" text,`+
			`"retries" integer NOT NULL DEFAULT 0,`+
			`"lease_token" varchar(32),`+
			`"lease_until" timestamptz,`+
			`"next_attempt_at" timestamptz NOT NULL,`+
			`"expired_at" timestamptz,`+
			`PRIMARY KEY ("id")`+
			")",
		table, statusType,
	)
}

func receivedCreateSQL(table, statusType string) string {
	return fmt.Sprintf(
		"CREATE TABLE IF NOT EXISTS %s ("+
			`"id" bigint GENERATED BY DEFAULT AS IDENTITY,`+
			`"created_at" timestamptz NOT NULL,`+
			`"version" varchar(16) NOT NULL,`+
			`"topic" varchar(256) NOT NULL,`+
			`"status" %s NOT NULL,`+
			`"headers" text,`+
			`"payload" text,`+
			`"retries" integer NOT NULL DEFAULT 0,`+
			`"lease_token" varchar(32),`+
			`"lease_until" timestamptz,`+
			`"next_attempt_at" timestamptz NOT NULL,`+
			`"expired_at" timestamptz,`+
			`"group" varchar(128) NOT NULL,`+
			`PRIMARY KEY ("id")`+
			")",
		table, statusType,
	)
}

func claimIndexSQL(quotedTable, index string) (string, error) {
	quotedIndex, err := quoteIdent(index)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf(
		`CREATE INDEX IF NOT EXISTS %s ON %s ("version", "status", "next_attempt_at", "lease_until", "retries")`,
		quotedIndex, quotedTable,
	), nil
}
